#!/usr/bin/env python3
"""Cells of record vs the amendment-(j) re-score (fresh_eval_<tag>_<mode>_v2): per comparison and mode, per-seed lists,
arm totals, Δ (human − machine), exact two-sided permutation p on per-seed counts (the registered statistic), plus the
pin / restore_failed / bank stamps, and the end-to-end reproduction guard (per-episode outcome/steps/contact/nested must
equal the record). usage: eval_fixes_table.py [runs_dir]   (prints markdown)"""
import glob, itertools, json, os, sys
root = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/wm_fix_2026-09-03/runs")
SEEDS = range(8)
# (label, human run pattern, [(machine label, machine run pattern, of_record?)], [(tag, success key)], primary tag)
FAM = [
    ("PLACE (§2/§2.y; amendment (e) matched 39; (i) polEdDP)", "s2_r2d_place_state_dH_bnormclamp1ent5_s%d",
     [("machine-39 (of record)", "s2_r2d_place_state_dDP_bnormclamp1ent5_n39_s%d"), ("machine-63 (descriptive)", "s2_r2d_place_state_dDP_bnormclamp1ent5_s%d")],
     [("polE", "placed_v2"), ("polEdDP", "placed_v2"), ("holdE", "placed_v2")], "polE"),
    ("CARRYCONTACT (§4; matched 21)", "s2_r2d_carrycontact_state_dH_bnormclamp1ent5_s%d",
     [("machine-21 (of record)", "s2_r2d_carrycontact_state_dDP_bnormclamp1ent5_n21_s%d")],
     [("polE", "contact"), ("polEdDP", "contact")], "polE"),
    ("CONTACT AFTER RELEASE (§3; amendment (f) polE_contact)", "s2_r2d_contact_state_dH_bnormclamp1ent5_subfloor_s%d",
     [("machine n11 (of record)", "s2_r2d_contact_state_dDP_bnormclamp1ent5_n11_s%d"), ("machine n25 (descriptive)", "s2_r2d_contact_state_dDP_bnormclamp1ent5_s%d")],
     [("polE", "contact")], "polE"),
]
E2E = ("END-TO-END (§5.1; amendment (d))", "full_r2d_state_dHfull_all_bnormclampS8ent5_s%d", "full_r2d_state_dDPfull_bnormclampS8ent5_s%d",
       ["rnd30", "hold15"], ["picked", "placed", "placed_v2", "contact", "contact_push", "nested", "nested_honest"])


def load(run, tag, mode, v2):
    f = os.path.join(root, run, f"fresh_eval_{tag}_{mode}" + ("_v2" if v2 else ""), "metrics.json")
    return json.load(open(f)) if os.path.exists(f) else None


def perm(a, b):
    obs = sum(a) / len(a) - sum(b) / len(b); pool = a + b; n = len(a); c = t = 0
    for idx in itertools.combinations(range(len(pool)), n):
        s = set(idx); x = [pool[i] for i in idx]; y = [pool[i] for i in range(len(pool)) if i not in s]
        t += 1; c += abs(sum(x) / n - sum(y) / len(y)) >= abs(obs) - 1e-12
    return obs, c / t


def cnt(m, key):
    pe = m["per_episode"]
    return sum(1 for e in pe if (e.get("stages") or {}).get(key) or (key == e.get("outcome"))), len(pe), sum(1 for e in pe if e.get("outcome") == "restore_failed")


def stamp(m):
    return dict(fix=m.get("eval_fixes"), pinned=m.get("entries_pinned"), bank=os.path.basename(m.get("bank_path") or "") or None,
                bank_version=m.get("bank_version"), sha=(m.get("bank_sha256") or "")[:8] or None, shelf=m.get("world_shelf_top_z"), pin=m.get("pin_stats"))


findings, pending = [], []
print("# Cells of record vs amendment-(j) re-score (generated by eval_fixes_table.py)\n")
for label, hp, machines, tags, primary in FAM:
    print(f"## {label}\n")
    for tag, key in tags:
        for mode in ("mode", "sample"):
            star = " **(primary)**" if (tag == primary and mode == "mode") else ""
            print(f"### {tag} {mode.upper()}{star}\n")
            print("| arm | seeds | record: per-seed | record total | re-scored: per-seed | re-scored total | Δ total (re − rec) | rf record → re-scored |")
            print("|---|---|---|---|---|---|---|---|")
            table = {}
            for arm, pat in [("human", hp)] + machines:
                rec, new = [], []
                for s in SEEDS:
                    r = load(pat % s, tag, mode, False); v = load(pat % s, tag, mode, True)
                    if r is None: continue
                    if v is None: pending.append(f"{pat % s} {tag} {mode}"); continue
                    st = stamp(v)
                    if st["fix"] != "j" or not st["pinned"]: findings.append(f"STAMP {pat % s} {tag} {mode}: {st}")
                    if tag.startswith("polE") and st["bank_version"] is None: findings.append(f"BANK not rebuilt in {pat % s} {tag} {mode}: {st}")
                    rec.append(cnt(r, key)); new.append(cnt(v, key))
                if not rec: continue
                if not new: print(f"| {arm} | {len(rec)} | {[x[0] for x in rec]} | {sum(x[0] for x in rec)}/{sum(x[1] for x in rec)} | pending | — | — | — |"); continue
                R, N = sum(x[0] for x in rec), sum(x[1] for x in rec); R2, N2 = sum(x[0] for x in new), sum(x[1] for x in new)
                print(f"| {arm} | {len(new)} | {[x[0] for x in rec]} | {R}/{N} ({R/N:.3f}) | {[x[0] for x in new]} | {R2}/{N2} ({R2/N2:.3f}) | {R2/N2 - R/N:+.3f} | {sum(x[2] for x in rec)} → {sum(x[2] for x in new)} |")
                table[arm] = (rec, new, N // max(len(rec), 1))
            h = table.get("human")
            for arm, _ in machines:
                mm = table.get(arm)
                if not h or not mm: continue
                for which, idx in (("record", 0), ("re-scored", 1)):
                    a = [x[0] for x in h[idx]]; b = [x[0] for x in mm[idx]]
                    if len(a) >= 2 and len(b) >= 2:
                        o, p = perm(a, b); n_ep = h[2]
                        print(f"- {which}: human {a} vs {arm} {b} → Δ(human − machine) = {o/n_ep:+.3f} (per-seed count {o:+.2f} of {n_ep}), exact two-sided perm p = {p:.3f} (n = {len(a)} v {len(b)})")
                if len(h[1]) >= 2 and len(mm[1]) >= 2 and tag == primary and mode == "mode":
                    o, p = perm([x[0] for x in h[1]], [x[0] for x in mm[1]]); d = o / h[2]
                    print(f"- **verdict ({tag} MODE, {arm}): |Δ| = {abs(d):.3f} → registered |Δ| < 0.10 {'MET — the null survives' if abs(d) < 0.10 else 'NOT MET — the record is superseded'}**")
            print()
# end-to-end
label, hp, mp, sets, keys = E2E
print(f"## {label}\n")
for tag in sets:
    for mode in ("mode", "sample"):
        star = " **(primary)**" if (tag == "rnd30" and mode == "mode") else ""
        print(f"### {tag} {mode.upper()}{star}\n")
        print("| arm | seeds | " + " | ".join(f"{k} rec → re" for k in keys) + " | outcomes_honest (re) |"); print("|---|---|" + "---|" * (len(keys) + 1))
        arms = {}
        for arm, pat in (("human", hp), ("machine", mp)):
            rows = []
            for s in SEEDS:
                r = load(pat % s, tag, mode, False); v = load(pat % s, tag, mode, True)
                if r is None: continue
                if v is None: pending.append(f"{pat % s} {tag} {mode}"); continue
                pr, pv = r["per_episode"], v["per_episode"]
                bad = [e["ep"] for e, f in zip(pr, pv) if e["outcome"] != f["outcome"] or e["steps"] != f["steps"]
                       or bool(e["stages"]["contact"]) != bool(f["stages"]["contact"]) or bool(e["stages"]["nested"]) != bool(f["stages"]["nested"])]
                if bad or len(pr) != len(pv): findings.append(f"E2E REPRO MISMATCH {pat % s} {tag} {mode}: episodes {bad} (n {len(pr)} v {len(pv)})")
                st = stamp(v)
                if st["fix"] != "j": findings.append(f"STAMP {pat % s} {tag} {mode}: {st}")
                rows.append(dict(seed=s, n=len(pv), rec={k: sum(1 for e in pr if (e.get("stages") or {}).get(k)) for k in keys},
                                 new={k: sum(1 for e in pv if (e.get("stages") or {}).get(k)) for k in keys}, oh=v.get("outcomes_honest")))
            arms[arm] = rows
            if rows:
                N = sum(x["n"] for x in rows)
                oh = {}
                for x in rows:
                    for k, c in (x["oh"] or {}).items(): oh[k] = oh.get(k, 0) + c
                print(f"| {arm} | {len(rows)} | " + " | ".join(f"{sum(x['rec'][k] for x in rows)}/{N} → {sum(x['new'][k] for x in rows)}/{N} ({sum(x['new'][k] for x in rows)/N:.3f})" for k in keys) + f" | {oh} |")
        for arm in ("human", "machine"):
            if arms.get(arm): print(f"\n- per-seed {arm}: " + "; ".join(f"{k} {[x['new'][k] for x in arms[arm]]}" for k in keys))
        a, b = arms.get("human", []), arms.get("machine", [])
        if len(a) >= 2 and len(b) >= 2:
            n_ep = a[0]["n"]
            for k in keys:
                o, p = perm([x["new"][k] for x in a], [x["new"][k] for x in b]); ra = sum(x["new"][k] for x in a) / (n_ep * len(a)); rb = sum(x["new"][k] for x in b) / (n_ep * len(b))
                reach = max(ra, rb) >= 0.2
                print(f"- {k}: human {ra:.3f} vs machine {rb:.3f} → Δ = {o/n_ep:+.3f}, exact p = {p:.3f}" + (f"  [(d) P2 stage reached ≥ 0.2: |Δ| < 0.10 {'MET' if abs(o/n_ep) < 0.10 else 'NOT MET'}]" if reach else "  [below 0.2 in both arms: P2 not applicable]"))
            if tag == "rnd30" and mode == "mode":
                ra = sum(x["new"]["nested_honest"] for x in a) / (n_ep * len(a)); rb = sum(x["new"]["nested_honest"] for x in b) / (n_ep * len(b))
                print(f"- **(d) P3 on nested_honest: human {ra:.3f}, machine {rb:.3f} → nested < 0.2 both arms {'MET' if max(ra, rb) < 0.2 else 'NOT MET'}**")
        print()
if pending: print(f"\n## pending re-score cells ({len(pending)})\n\n" + "\n".join(f"- {p}" for p in pending))
print(f"\n## reproduction guard / stamp findings ({len(findings)})\n\n" + ("\n".join(f"- {f}" for f in findings) if findings else "- every end-to-end `_v2` cell reproduced the record's per-episode outcome / steps / contact / nested; every cell carries eval_fixes='j' and a rebuilt bank where applicable"))
